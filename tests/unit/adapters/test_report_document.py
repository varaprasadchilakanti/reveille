"""The report reads as a document that can be passed on: it says what made it and
from which commit, lists its sections, and prints with margins and page numbers.

A forwarded report said "Generated by Reveille" and nothing else: not which
version, not which commit, so a reader could not check it against the
repository. A printed one had no page numbers, and the profile table broke
across two sheets mid-row.
"""

from __future__ import annotations

import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from tests.unit.adapters.test_report_layout import (  # noqa: F401
    _function,
    _print_rule,
    _print_rules,
    rendered,
)

_TEMPLATE = Path(__file__).resolve().parents[3] / "src/reveille/templates/report.html.j2"


def _footer(rendered: str) -> str:  # noqa: F811
    footer = re.search(r'<footer class="report-footer">(.*?)</footer>', rendered, re.DOTALL)
    assert footer, "the report has no footer"
    return " ".join(re.sub(r"<[^>]+>", "", footer.group(1)).split())


@pytest.mark.unit
class TestTheReportSaysWhatMadeIt:
    def test_the_footer_names_the_version_the_time_and_the_commit(
        self,
        rendered: str,  # noqa: F811
    ) -> None:
        footer = _footer(rendered)

        assert re.search(
            r"Generated by Reveille \d+\.\d+\.\d+\S* on \d{4}-\d\d-\d\d \d\d:\d\d UTC", footer
        )
        assert re.search(r"from commit [0-9a-f]{12}\.", footer)
        assert "Computed offline from Git history." in footer

    def test_the_header_names_the_commit(self, rendered: str) -> None:  # noqa: F811
        header = re.search(r'<header class="report-header">(.*?)</header>', rendered, re.DOTALL)
        assert header
        assert re.search(r"<strong>Commit:</strong> <code>[0-9a-f]{12}</code>", header.group(1))


@pytest.mark.unit
class TestTheContentsList:
    def test_it_is_hidden_until_the_script_fills_it(self, rendered: str) -> None:  # noqa: F811
        """Without JavaScript an empty list would show only the word "Contents"."""
        assert re.search(
            r'<nav id="contents" class="report-contents" aria-labelledby="contents-label" hidden>',
            rendered,
        )
        assert '<span id="contents-label" class="report-contents-label">Contents</span>' in rendered

    def test_paper_leaves_it_out(self, rendered: str) -> None:  # noqa: F811
        """Links cannot be followed on paper, and the list gives no page numbers."""
        assert "display: none" in _print_rule(rendered, ".report-contents")

    def test_the_page_fills_it_when_it_loads(self, rendered: str) -> None:  # noqa: F811
        """Calling the builder in a test proves nothing if the page never calls it."""
        loaded = rendered.index("document.addEventListener('DOMContentLoaded'")
        handler = _function(rendered[loaded:], "")
        assert "buildContents();" in handler

    def test_it_lists_the_caveats_panel(self, rendered: str) -> None:  # noqa: F811
        """The panel exists because documentation does not travel with the file;
        a contents list that skipped it led a reader straight past it."""
        assert '<h2 id="caveats-title">' in rendered
        builder = _function(rendered, "buildContents")
        assert "document.querySelectorAll('#caveats-title, h2.section-title')" in builder

    def test_it_keeps_list_semantics_without_bullets(self, rendered: str) -> None:  # noqa: F811
        assert '<ol role="list"></ol>' in rendered


def _build_contents(headings: list[dict[str, str]]) -> dict:
    """Run the template's `buildContents` against stand-in headings and nav."""
    source = _TEMPLATE.read_text(encoding="utf-8")
    function = re.search(r"    function buildContents\(.*?\n    \}\n", source, re.DOTALL)
    assert function, "buildContents is missing from the template"
    script = (
        "var items = [];\n"
        "var list = {appendChild: function (item) { items.push(item); }};\n"
        "var nav = {hidden: true, querySelector: function () { return list; }};\n"
        f"var headings = {json.dumps(headings)}.map(function (h) {{\n"
        "  return {id: h.id, firstChild: {textContent: h.text}}; });\n"
        "function element() { return {children: [], appendChild: function (c) { this.children.push(c); }}; }\n"
        "var document = {\n"
        "  getElementById: function () { return nav; },\n"
        "  querySelectorAll: function () { return headings; },\n"
        "  createElement: element};\n" + function.group(0) + "buildContents();\n"
        "process.stdout.write(JSON.stringify({hidden: nav.hidden,\n"
        "  ids: headings.map(function (h) { return h.id; }),\n"
        "  links: items.map(function (i) {\n"
        "    var a = i.children[0]; return [a.href, a.textContent]; })}));\n"
    )
    node = shutil.which("node")
    assert node
    result = subprocess.run([node, "-e", script], check=True, capture_output=True, text=True)
    return json.loads(result.stdout)


@pytest.mark.unit
@pytest.mark.skipif(shutil.which("node") is None, reason="needs Node.js to run the contents code")
class TestBuildingTheContents:
    def test_each_section_heading_becomes_a_link_to_it(self) -> None:
        built = _build_contents(
            [{"id": "", "text": "  What the History Shows "}, {"id": "", "text": "Contributors"}]
        )

        assert built["hidden"] is False
        assert built["ids"] == ["section-1", "section-2"]
        assert built["links"] == [
            ["#section-1", "What the History Shows"],
            ["#section-2", "Contributors"],
        ]

    def test_a_heading_keeps_an_id_it_already_has(self) -> None:
        built = _build_contents([{"id": "caveats", "text": "Read Before"}])

        assert built["links"] == [["#caveats", "Read Before"]]

    def test_a_report_with_no_sections_shows_no_list(self) -> None:
        assert _build_contents([])["hidden"] is True


@pytest.mark.unit
class TestPrintedPages:
    def test_each_sheet_is_numbered(self, rendered: str) -> None:  # noqa: F811
        rules = _print_rules(rendered)

        assert "@page" in rules
        assert 'content: "Page " counter(page) " of " counter(pages);' in rules

    def test_the_reader_chooses_the_paper(self, rendered: str) -> None:  # noqa: F811
        """A declared size takes A4 or Letter out of the print dialog's hands."""
        page = re.search(r"@page \{(.*?)@bottom-left", _print_rules(rendered))
        assert page
        assert "size:" not in page.group(1)

    def test_the_margin_text_is_the_secondary_text_colour(self, rendered: str) -> None:  # noqa: F811
        """A page box cannot read the custom properties, so the grey is written out;
        it must stay the print palette's secondary text colour, which the
        contrast tests measure."""
        rules = _print_rules(rendered)
        secondary = re.search(r"--color-text-secondary: (#[0-9a-f]{6});", rules)
        assert secondary
        boxes = re.findall(r"@bottom-(?:left|right) \{([^{}]*)\}", rules)
        assert len(boxes) == 2
        for box in boxes:
            assert re.findall(r"(?<![-\w])color: ([^;]+);", box) == [secondary.group(1)]

    @pytest.mark.parametrize("selector", ["table.profile tr", ".findings li", ".caveats"])
    def test_a_row_or_finding_is_not_split_across_sheets(
        self,
        rendered: str,  # noqa: F811
        selector: str,
    ) -> None:
        assert "break-inside: avoid" in _print_rule(rendered, selector)
